const manifest = await read('dist/.vite/manifest.json');
const rendererClosures = [];
for (const key of Object.keys(manifest).filter(k => /mermaid.core.mjs$|pele\/dist\/(pele.js|esm\/lazy.js)$/.test(k))) {
  for (const dynamic of [false, true]) {
    const seen = new Set();
    function visit(k) {
      if (seen.has(k)) return;
      seen.add(k);
      const entry = manifest[k];
      for (const dep of [...(entry?.imports ?? []), ...(dynamic ? (entry?.dynamicImports ?? []) : [])]) visit(dep);
    }
    visit(key);
    const names = new Set([...seen].map(k => manifest[k]?.file?.replace('assets/', '')));
    const files = d.bytes.filter(b => names.has(b.file));
    rendererClosures.push({
      entry: key,
      dynamic,
      files: files.map(f => f.file),
      ...Object.fromEntries(['raw', 'gzip', 'brotli'].map(key => [key, files.reduce((a, b) => a + b[key], 0)])),
    });
  }
}
const studioManifest = await read('../../dist/.vite/manifest.json');
const studioChunks = [];
for (const file of new Set(
  Object.values(studioManifest)
    .map(e => e.file)
    .filter(f => f.endsWith('.js')),
)) {
  const bytes = await readFile(new URL('../../dist/' + file, import.meta.url));
  studioChunks.push({ file, raw: bytes.length, gzip: gzipSync(bytes).length });
}
await writeFile(
  new URL('evidence/builds.json', import.meta.url),
  JSON.stringify({ rendererClosures, studioChunks }, null, 2),
);
await copyFile(
  new URL('../../dist/.vite/manifest.json', import.meta.url),
  new URL('evidence/studio-manifest.json', import.meta.url),
);
